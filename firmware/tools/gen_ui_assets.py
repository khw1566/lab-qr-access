"""Convert PC-rendered icon images to native LVGL image data."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/source'
OUT = ROOT / 'main/assets'
ICONS = ('scan-qr-code', 'house', 'settings', 'circle-help', 'smartphone', 'user-round',
         'calendar-check-2', 'circle-check', 'circle-x', 'wifi', 'wifi-off',
         'chevron-right', 'fingerprint')
ICON_SIZE = 128


def rgb565(image):
    data = bytearray()
    for r, g, b in image.convert('RGB').getdata():
        value = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        data.extend((value & 255, value >> 8))
    return data


def descriptor(name, filename, width, height, alpha=False):
    symbol = '_binary_' + filename.replace('.', '_') + '_start'
    return [f'extern const uint8_t {name}_bytes[] asm("{symbol}");',
            f'const lv_image_dsc_t {name} = {{',
            f'    .header = {{.magic=LV_IMAGE_HEADER_MAGIC, .cf=LV_COLOR_FORMAT_{"RGB565A8" if alpha else "RGB565"},',
            f'               .w={width}, .h={height}, .stride={width * 2}}},',
            f'    .data_size={width * height * (3 if alpha else 2)}, .data={name}_bytes,',
            '};', '']


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    code = ['/* Generated by tools/gen_ui_assets.py. */', '#include "ui_assets.h"', '']
    for i, name in enumerate(ICONS):
        icon = Image.open(SOURCE / f'{name}.png').convert('RGBA').resize((ICON_SIZE, ICON_SIZE), Image.Resampling.LANCZOS)
        alpha = icon.getchannel('A')
        # The common white RGB plane is recolored by LVGL; alpha preserves smooth edges.
        data = rgb565(Image.new('RGB', (ICON_SIZE, ICON_SIZE), 'white')) + alpha.tobytes()
        (OUT / f'icon_{i}.rgb565a8').write_bytes(data)
        code += descriptor(f'icon_{i}', f'icon_{i}.rgb565a8', ICON_SIZE, ICON_SIZE, True)
        if name in ('fingerprint', 'circle-help', 'settings'):
            background = '#0070c0' if name == 'fingerprint' else '#adadad' if name == 'circle-help' else '#ffffff'
            foreground = '#000000' if name == 'settings' else '#ffffff'
            jpg = Image.new('RGB', (ICON_SIZE, ICON_SIZE), background)
            jpg.paste(Image.new('RGB', jpg.size, foreground), (0, 0), alpha)
            jpg.save(SOURCE / f'{name}.jpg', quality=98, subsampling=0)
    code += ['const lv_image_dsc_t *const ui_icon_images[] = {',
             '    ' + ', '.join(f'&icon_{i}' for i in range(len(ICONS))), '};', '']
    (ROOT / 'main/ui_assets.c').write_text('\n'.join(code), encoding='utf-8')
    (ROOT / 'main/ui_assets.h').write_text('#pragma once\n#include "lvgl.h"\nextern const lv_image_dsc_t *const ui_icon_images[13];\n', encoding='utf-8')
    print(f'Converted {len(ICONS)} icons at 128px; JPEG originals retained.')


if __name__ == '__main__':
    main()
