"""Convert PC-rendered icon images to native LVGL image data."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/source'
OUT = ROOT / 'main/assets'
ICONS = ('scan-qr-code', 'house', 'settings', 'circle-help', 'smartphone', 'user-round',
         'calendar-check-2', 'circle-check', 'circle-x', 'wifi', 'wifi-off',
         'chevron-right', 'fingerprint')
ICON_SIZE = 128
ICON_SIZES = (20, 28, 44, 52, 56, 64, 80, 128)


def descriptor(name, filename, size, offset):
    symbol = '_binary_' + filename.replace('.', '_') + '_start'
    return [f'static const lv_image_dsc_t {name}_{size} = {{',
            f'    .header = {{.magic=LV_IMAGE_HEADER_MAGIC, .cf=LV_COLOR_FORMAT_A8,',
            f'               .w={size}, .h={size}, .stride={size}}},',
            f'    .data_size={size * size}, .data={name}_bytes + {offset},',
            '};', '']


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    code = ['/* Generated by tools/gen_ui_assets.py. */', '#include "ui_assets.h"', '']
    for i, name in enumerate(ICONS):
        icon = Image.open(SOURCE / f'{name}.png').convert('RGBA')
        code += [f'extern const uint8_t icon_{i}_bytes[] asm("_binary_icon_{i}_a8_start");']
        data = bytearray()
        for size in ICON_SIZES:
            alpha = icon.resize((size, size), Image.Resampling.LANCZOS).getchannel('A')
            code += descriptor(f'icon_{i}', f'icon_{i}.a8', size, len(data))
            data.extend(alpha.tobytes())
        (OUT / f'icon_{i}.a8').write_bytes(data)
        if name in ('fingerprint', 'circle-help', 'settings'):
            alpha = icon.resize((ICON_SIZE, ICON_SIZE), Image.Resampling.LANCZOS).getchannel('A')
            background = '#0070c0' if name == 'fingerprint' else '#adadad' if name == 'circle-help' else '#ffffff'
            foreground = '#000000' if name == 'settings' else '#ffffff'
            jpg = Image.new('RGB', (ICON_SIZE, ICON_SIZE), background)
            jpg.paste(Image.new('RGB', jpg.size, foreground), (0, 0), alpha)
            jpg.save(SOURCE / f'{name}.jpg', quality=98, subsampling=0)
    code += ['static const unsigned icon_sizes[] = {' + ', '.join(map(str, ICON_SIZES)) + '};',
             'static const lv_image_dsc_t *const images[13][8] = {']
    code += ['    {' + ', '.join(f'&icon_{i}_{size}' for size in ICON_SIZES) + '},' for i in range(len(ICONS))]
    code += ['};', 'const lv_image_dsc_t *ui_icon_asset(unsigned icon, unsigned size)', '{',
             '    if (icon >= 13) icon = 0;',
             '    unsigned closest = 0, difference = 0xffffffffu;',
             '    for (unsigned i = 0; i < 8; i++) {',
             '        unsigned d = size > icon_sizes[i] ? size - icon_sizes[i] : icon_sizes[i] - size;',
             '        if (d < difference) { closest = i; difference = d; }',
             '    }', '    return images[icon][closest];', '}', '']
    (ROOT / 'main/ui_assets.c').write_text('\n'.join(code), encoding='utf-8')
    (ROOT / 'main/ui_assets.h').write_text('#pragma once\n#include "lvgl.h"\nconst lv_image_dsc_t *ui_icon_asset(unsigned icon, unsigned size);\n', encoding='utf-8')
    print(f'Converted {len(ICONS)} icons at {ICON_SIZES}; native A8 sizes, no device scaling.')


if __name__ == '__main__':
    main()
